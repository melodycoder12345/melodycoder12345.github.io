import { loadKnowledge } from './knowledge-lib.js';

export function generateKnowledgeData(knowledge = loadKnowledge()) {
  const { modules, nodes, relations, relationTypes } = knowledge;
  const edges = relations.map(({ source, target }) => [source, target]);
  const profiles = nodes.filter(node => node.type === 'page').map(node => ({
    id: node.id,
    href: node.href,
    title: node.label,
    module: node.module,
    kind: node.kind,
    level: node.level,
    presentations: node.presentations,
    interaction: node.interaction,
    embeddedDemos: node.embeddedDemos,
    learning: node.learning,
  }));

  return `// Generated by npm run knowledge:build. Edit files under knowledge/ instead.\n` +
  `(function (window) {\n` +
  `  'use strict';\n` +
  `  window.GRAPH_MODULES = Object.freeze(${serialize(modules)});\n` +
  `  window.GRAPH_NODES = Object.freeze(${serialize(nodes)});\n` +
  `  window.GRAPH_EDGES = Object.freeze(${serialize(edges)});\n` +
  `  window.KNOWLEDGE_RELATION_TYPES = Object.freeze(${serialize(relationTypes)});\n` +
  `  window.KNOWLEDGE_RELATIONS = Object.freeze(${serialize(relations)});\n` +
  `  window.PAGE_PROFILES = Object.freeze(${serialize(profiles)});\n` +
  `  var byId = new Map(window.PAGE_PROFILES.map(function (profile) { return [profile.id, profile]; }));\n` +
  `  var byHref = new Map(window.PAGE_PROFILES.map(function (profile) { return [profile.href.replace(/^\\.\\//, ''), profile]; }));\n` +
  `  window.getPageProfile = function (idOrHref) {\n` +
  `    if (typeof idOrHref !== 'string') return null;\n` +
  `    var normalized = idOrHref.replace(/^\\.\\//, '').split(/[?#]/)[0];\n` +
  `    return byId.get(idOrHref) || byHref.get(normalized) || null;\n` +
  `  };\n` +
  `})(window);\n`;
}

function serialize(value) {
  return JSON.stringify(value, null, 2).replace(/^/gm, '  ').trimStart();
}
